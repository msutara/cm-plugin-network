func TestParseHexIP(t *testing.T) {
	cases := []struct {
		hex  string
		want string
	}{
		{"0101A8C0", "192.168.1.1"},
		{"00000000", "0.0.0.0"},
		{"0100007F", "127.0.0.1"},
	}
	for _, tc := range cases {
		t.Run(tc.hex, func(t *testing.T) {
			got := parseHexIP(tc.hex)
			if got != tc.want {
				t.Errorf("got %q, want %q", got, tc.want)
			}
		})
	}
}

