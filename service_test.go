func TestListInterfaces(t *testing.T) {
	svc := NewService()
	ifaces, err := svc.ListInterfaces()
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	if ifaces == nil {
		t.Fatal("expected non-nil slice")
	}
	// Every system should have at least one non-loopback interface
	// (may be zero in some CI containers, so don't assert count)
	for _, iface := range ifaces {
		if iface.Name == "" {
			t.Error("interface with empty name")
		}
		if iface.State != "up" && iface.State != "down" {
			t.Errorf("interface %s: unexpected state %q", iface.Name, iface.State)
		}
	}
}

