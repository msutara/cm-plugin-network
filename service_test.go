func TestValidateStaticIPRequest(t *testing.T) {
	cases := []struct {
		name    string
		req     StaticIPRequest
		wantErr error
	}{
		{"valid", StaticIPRequest{IP: "192.168.1.10/24", Gateway: "192.168.1.1"}, nil},
		{"empty_ip", StaticIPRequest{IP: "", Gateway: "192.168.1.1"}, errEmptyIP},
		{"empty_gw", StaticIPRequest{IP: "192.168.1.10/24", Gateway: ""}, errEmptyGateway},
		{"bad_cidr", StaticIPRequest{IP: "192.168.1.10", Gateway: "192.168.1.1"}, errInvalidCIDR},
		{"bad_gw", StaticIPRequest{IP: "192.168.1.10/24", Gateway: "not-an-ip"}, errInvalidGW},
		{"ipv6_gw", StaticIPRequest{IP: "192.168.1.10/24", Gateway: "::1"}, errIPv6NotSupported},
		{"cidr_v6", StaticIPRequest{IP: "::1/128", Gateway: "192.168.1.1"}, errIPv6NotSupported},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			err := validateStaticIPRequest(tc.req)
			if err != tc.wantErr {
				t.Errorf("got %v, want %v", err, tc.wantErr)
			}
		})
	}
}

